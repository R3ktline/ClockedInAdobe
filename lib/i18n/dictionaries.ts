export const DICTIONARIES: Record<Lang, Dict> = { en, ro, de, fr, es, it };

export function translate(lang: Lang, key: string, vars?: Vars, fallback?: string): string {
  const template = DICTIONARIES[lang]?.[key] ?? DICTIONARIES[DEFAULT_LANG][key] ?? fallback ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

